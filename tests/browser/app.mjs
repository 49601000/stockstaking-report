import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import * as XLSX from 'xlsx';
import {testDriveBrowser} from './drive.mjs';
const baseURL=process.env.APP_URL || 'http://127.0.0.1:4173';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(baseURL);
 assert.equal(await page.locator('#export-csv').isDisabled(),true);
 await page.locator('#sample').click();
 await page.waitForFunction(()=>document.querySelector('#count').textContent.includes('1,348'));
 assert.equal(await page.locator('#file-count').textContent(),'3');
 await page.locator('#status').selectOption('保留');
 assert.match(await page.locator('#count').textContent(),/^5 /);
 await page.locator('[data-key]').first().click();
 const reviewNote='ブラウザテスト：対応記録保存, "確認済み"\n次の行も保持';
 await page.locator('#note').fill(reviewNote);
 await page.locator('#reason').selectOption('その他');
 await page.locator('#reviewed').check();
 await page.locator('#edit button').click();
 assert.match(await page.locator('#table').textContent(),/✓ 完了/);
 await page.locator('#unresolved').check();
 assert.match(await page.locator('#count').textContent(),/^4 /);
 await page.locator('[data-tab="memos"]').click();
 assert.match(await page.locator('#table').textContent(),/Winston 543/);
 // CSV must include both stores and every row even with filters and the memo tab active.
 const storeOptions=await page.locator('#store option').allTextContents();
 await page.locator('#store').selectOption(storeOptions[1]);
 const csvDownload=page.waitForEvent('download');await page.locator('#export-csv').click();
 mkdirSync('output/test-artifacts',{recursive:true});
 const csvPath='output/test-artifacts/棚卸照合_検証.csv';await (await csvDownload).saveAs(csvPath);
 const csvBytes=readFileSync(csvPath);
 assert.deepEqual([...csvBytes.subarray(0,3)],[0xef,0xbb,0xbf]);
 const csvBook=XLSX.read(csvBytes.toString('utf8'),{type:'string',raw:true});
 const csvRows=XLSX.utils.sheet_to_json(csvBook.Sheets[csvBook.SheetNames[0]]);
 assert.equal(csvRows.length,1348);
 assert.deepEqual([...new Set(csvRows.map(r=>r['店舗']))].sort(),storeOptions.slice(1).sort());
 const reviewedRow=csvRows.find(r=>r['対応メモ']===reviewNote);
 assert.ok(reviewedRow);assert.equal(reviewedRow['確認理由'],'その他');assert.equal(reviewedRow['照合完了'],'完了');
 // Clear synthetic review before validating the exported workbook.
 await page.evaluate(()=>localStorage.clear());
 await page.reload();await page.locator('#sample').click();
 await page.waitForFunction(()=>document.querySelector('#count').textContent.includes('1,348'));
 await page.locator('#status').selectOption('保留');
 const downloaded=page.waitForEvent('download');await page.locator('#export').click();
 mkdirSync('output/test-artifacts',{recursive:true});const path='output/test-artifacts/棚卸照合_検証.xlsx';await (await downloaded).saveAs(path);
 const wb=XLSX.read(readFileSync(path),{type:'buffer'});
 assert.equal(wb.SheetNames.length,8);
 const rows=XLSX.utils.sheet_to_json(wb.Sheets['商品照合']);
 assert.equal(rows.length,1348);assert.equal(rows.filter(r=>r['棚卸確認状態']==='保留').length,5);
 assert.equal(rows.filter(r=>r['照合完了']==='完了').length,0);
 assert.equal(XLSX.utils.sheet_to_json(wb.Sheets['棚卸明細履歴']).length,1331);
 assert.equal(XLSX.utils.sheet_to_json(wb.Sheets['在庫明細履歴']).length,1345);
 assert.equal(XLSX.utils.sheet_to_json(wb.Sheets['ブランドメモ']).length,1);
 await page.locator('#status').selectOption('');
 await page.screenshot({path:'output/test-artifacts/画面プレビュー.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: browser import, filters, review, brand memo, CSV both stores / 1348 rows / BOM / multiline memo, XLSX 8 sheets / 1348 rows, mobile layout');
 await testDriveBrowser(browser,baseURL);
} finally {await browser.close();}
